import assert from 'node:assert/strict';
import { createElement } from 'react';
import { renderToStaticMarkup } from 'react-dom/server';
import AiMarkdown, { safeMarkdownUrl } from '../../components/AiMarkdown';
import InsightPanel from '../../components/InsightPanel';
import type { ZiweiChart } from '../../lib/ziwei/types';
const md = '# 标题\n\n- 项目 **加粗**\n- 第二项\n\n|维度|解读|\n|---|---|\n|命格|示例|\n\n```ts\nconst x = 1;\n```\n\n[安全链接](https://example.com)';
const html=renderToStaticMarkup(createElement(AiMarkdown,{text:md}));
for(const tag of ['<h2','<ul','<strong','<table','<pre','<code'])assert.ok(html.includes(tag),tag);
assert.ok(html.includes('rel="noopener noreferrer"'));
const unsafe=renderToStaticMarkup(createElement(AiMarkdown,{text:'<script>alert(1)</script>\n\n<img src=x onerror=alert(1)>\n\n[危险](javascript:alert(1))\n\n[编码](java&#x73;cript:alert(1))\n\n![追踪](https://tracker.example/pixel)'}));
assert.ok(!/<script|<img|onerror=|href="javascript:/i.test(unsafe),unsafe);
for(const url of ['javascript:alert(1)','data:text/html,x','vbscript:x','//evil.example','/\\evil.example','java\u0000script:alert(1)'])assert.equal(safeMarkdownUrl(url),'');
assert.equal(safeMarkdownUrl('https://example.com/path'),'https://example.com/path');
assert.doesNotThrow(()=>renderToStaticMarkup(createElement(AiMarkdown,{text:'## 流式标题\n\n**尚未完成\n\n|A|B|\n|---|---|\n|部'})));
const fixture={birthInfo:{year:1990},palaces:[]} as unknown as ZiweiChart;
const manual=renderToStaticMarkup(createElement(InsightPanel,{chart:fixture,autoStart:false}));
assert.ok(manual.includes('开始解读'));assert.ok(manual.includes('type="password"'));assert.ok(manual.includes('配置完成后点击'));
console.log('Markdown/UI passed: GFM table/title/list/bold/code, safe links, no raw HTML/XSS or tracking images, partial-stream render and explicit unconfigured start button. Browser interactions not exercised.');
